#!/usr/bin/env bash
# Usage:
#   ./deploy.sh infra                  terraform plan + apply (asks before applying)
#   ./deploy.sh bootstrap [args...]    first run: open SSH to your current IP, configure the
#                                      host over its public IP (installs Tailscale), close SSH again
#   ./deploy.sh configure [args...]    normal runs, over Tailscale; extra args go to
#                                      ansible-playbook (e.g. --tags calagopus, --check --diff)
#
# Env overrides: SSH_KEY (private key, default ~/.ssh/id_ed25519), MY_IP (bootstrap source IP),
#                TS_HOST (tailnet name of the server, default: tailscale_hostname from vars.yml)
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

SSH_KEY="${SSH_KEY:-$HOME/.ssh/id_ed25519}"
VARS_FILE="ansible/group_vars/all/vars.yml"

tf() { terraform -chdir=oci "$@"; }

die() { echo "error: $*" >&2; exit 1; }

preflight() {
  [[ -f "$VARS_FILE" ]] || die "$VARS_FILE missing (copy vars.yml.example)"
  [[ -f ansible/group_vars/all/vault.yml ]] || die "vault missing: run scripts/init-vault.sh"
  [[ -f ansible/.vault_pass ]] || die "ansible/.vault_pass missing"
  [[ "$(stat -c %a ansible/.vault_pass)" == 600 ]] || die "ansible/.vault_pass must be mode 600"
  [[ -f "$SSH_KEY" ]] || die "SSH key $SSH_KEY not found (set SSH_KEY)"
}

write_inventory() {
  cat > ansible/inventory.ini <<EOF
# Generated by deploy.sh
[gameserver]
calagopus ansible_host=$1 ansible_user=ubuntu ansible_ssh_private_key_file=$SSH_KEY
EOF
}

run_playbook() {
  (cd ansible && ansible-playbook site.yml "$@")
}

tf_apply_interactive() {
  tf init -input=false >/dev/null
  tf plan -out=tfplan "$@"
  read -rp "Apply this plan? [y/N] " answer
  [[ "$answer" == [yY] ]] || { rm -f oci/tfplan; die "aborted"; }
  tf apply tfplan
  rm -f oci/tfplan
}

case "${1:-}" in
  infra)
    tf_apply_interactive
    ;;

  bootstrap)
    preflight
    MY_IP="${MY_IP:-$(curl -fsS https://checkip.amazonaws.com)}"
    [[ "$MY_IP" =~ ^[0-9.]+$ ]] || die "could not determine your public IPv4 (set MY_IP)"
    echo "==> Temporarily allowing SSH from $MY_IP/32"
    tf_apply_interactive -var "ssh_bootstrap_cidrs=[\"$MY_IP/32\"]"
    trap 'echo "!! SSH is still open to $MY_IP/32. Run ./deploy.sh infra to close it." >&2' EXIT

    SERVER_IP="$(tf output -raw public_ip)"
    echo "==> Waiting for SSH on $SERVER_IP"
    for _ in $(seq 1 30); do
      ssh -i "$SSH_KEY" -o BatchMode=yes -o ConnectTimeout=5 -o StrictHostKeyChecking=accept-new \
        "ubuntu@$SERVER_IP" true 2>/dev/null && break
      sleep 5
    done

    write_inventory "$SERVER_IP"
    run_playbook "${@:2}"

    echo "==> Closing public SSH again (Tailscale is the way in from now on)"
    tf_apply_interactive -var 'ssh_bootstrap_cidrs=[]'
    trap - EXIT
    echo "==> Done. Next runs: ./deploy.sh configure"
    ;;

  configure)
    preflight
    TS_HOST="${TS_HOST:-$(sed -nE 's/^tailscale_hostname:[[:space:]]*"?([^"]+)"?.*/\1/p' "$VARS_FILE")}"
    [[ -n "$TS_HOST" ]] || die "tailscale_hostname not set in $VARS_FILE (or set TS_HOST)"
    write_inventory "$TS_HOST"
    run_playbook "${@:2}"
    ;;

  *)
    sed -n '2,9p' "$0" | sed 's/^# \{0,1\}//'
    exit 1
    ;;
esac
